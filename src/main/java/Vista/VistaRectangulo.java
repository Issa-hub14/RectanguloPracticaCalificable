    private void horizontalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_horizontalActionPerformed
        // TODO add your handling code here:
         if (!indiceValido()) return;
        if (valor.getText().trim().isEmpty()) {
            areaTexto1.setText("Ingrese el valor a mover.");
            return;
        }
        if (!esValido(valor.getText().trim())) {
            areaTexto1.setText("El valor debe ser numérico.");
            return;
        }
        double valo = Double.parseDouble(valor.getText().trim());
        if (valo == 0) {
            areaTexto1.setText("El valor debe ser diferente de cero.");
            return;
        }
        int indice = Integer.parseInt(indice1.getText().trim());
        areaTexto1.setText(controlador.moverHorizontal(indice, valo));
    }//GEN-LAST:event_horizontalActionPerformed

    private void contienePuntoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_contienePuntoActionPerformed
        // TODO add your handling code here:
        if (!indiceValido()) return;
        if (px.getText().trim().isEmpty() || py.getText().trim().isEmpty()) {
            areaTexto1.setText("Ingrese las coordenadas del punto.");
            return;
        }
        if (!esValido(px.getText().trim()) ||
            !esValido(py.getText().trim())) {
            areaTexto1.setText("Las coordenadas del punto deben ser numéricas.");
            return;
        }
        int indice = Integer.parseInt(indice1.getText().trim());
        areaTexto1.setText(controlador.contienePunto(indice,
            Double.parseDouble(px.getText().trim()),
            Double.parseDouble(py.getText().trim())));
    }//GEN-LAST:event_contienePuntoActionPerformed

    private void eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_eliminarActionPerformed
        // TODO add your handling code here:
        if (!indiceValido()) return;
        int indice = Integer.parseInt(indice1.getText().trim());
        areaTexto1.setText(controlador.eliminar(indice));
    }//GEN-LAST:event_eliminarActionPerformed

