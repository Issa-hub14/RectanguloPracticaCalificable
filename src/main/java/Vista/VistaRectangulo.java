    private void escalarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_escalarActionPerformed
        // TODO add your handling code here:
        if (!indiceValido()) return;
        if (factor.getText().trim().isEmpty()) {
            areaTexto1.setText("Ingrese el factor de escala.");
            return;
        }
        if (!esValido(factor.getText().trim())) {
            areaTexto1.setText("El factor debe ser un valor numérico.");
            return;
        }
        int indice = Integer.parseInt(indice1.getText().trim());
        areaTexto1.setText(controlador.escalar(indice,
            Double.parseDouble(factor.getText().trim())));
    }//GEN-LAST:event_escalarActionPerformed

    private void verticalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_verticalActionPerformed
        // TODO add your handling code here:
        if (!indiceValido()) return;
        if (valor.getText().trim().isEmpty()) {
            areaTexto1.setText("Ingrese el valor a mover.");
            return;
        }
        if (!esValido(valor.getText().trim())) {
            areaTexto1.setText("El valor debe ser numérico.");
            return;
        }
        double valo = Double.parseDouble(valor.getText().trim());
        if (valo == 0) {
            areaTexto1.setText("El valor debe ser diferente de cero.");
            return;
        }
        int indice = Integer.parseInt(indice1.getText().trim());
        areaTexto1.setText(controlador.moverVertical(indice, valo));
    }//GEN-LAST:event_verticalActionPerformed

    private void agregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_agregarActionPerformed
        // TODO add your handling code here:
        if (camposAgregarVacios()) {
            return;
        }
        if (!camposAgregarValidos()) {
            return;
        }

        String resultado = controlador.agregarRectangulo(
                Double.parseDouble(x1.getText().trim()),
                Double.parseDouble(y1.getText().trim()),
                Double.parseDouble(x2.getText().trim()),
                Double.parseDouble(y2.getText().trim())
        );
        areaTexto1.setText(resultado);
    }//GEN-LAST:event_agregarActionPerformed

