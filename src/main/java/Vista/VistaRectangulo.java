    private boolean esValido(String texto) {
        if (texto.isEmpty()) {
            return false;
        }
        int puntos = 0;
        for (int i = 0; i < texto.length(); i++) {
            char c = texto.charAt(i);
            if (c == '-' && i == 0) {
                continue;
            } else if (c == '.') {
                puntos++;
                if (puntos > 1) {
                    return false;
                }
            } else if (!Character.isDigit(c)) {
                return false;
            }
        }
        return true;
    }

    private boolean camposAgregarValidos() {
        if (!esValido(x1.getText().trim())
                || !esValido(y1.getText().trim())
                || !esValido(x2.getText().trim())
                || !esValido(y2.getText().trim())) {
            areaTexto1.setText("Ingrese valores numéricos válidos.");
            return false;
        }
        return true;
    }

    private boolean camposAgregarVacios() {
        if (x1.getText().trim().isEmpty()
                || y1.getText().trim().isEmpty()
                || x2.getText().trim().isEmpty()
                || y2.getText().trim().isEmpty()) {
            areaTexto1.setText("Complete todos los campos del vértice.");
            return true;
        }
        return false;
    }
    
    private boolean indiceValido() {
        if (indice1.getText().trim().isEmpty()) {
            areaTexto1.setText("Ingrese el índice del rectángulo.");
            return false;
        }
        for (int i = 0; i < indice1.getText().trim().length(); i++) {
            if (!Character.isDigit(indice1.getText().trim().charAt(i))) {
                areaTexto1.setText("El índice debe ser un número entero.");
                return false;
            }
        }
        int indice = Integer.parseInt(indice1.getText().trim());
        if (indice < 0 || indice >= controlador.getContador()) {
            areaTexto1.setText("El índice no existe.");
            return false;
        }
        return true;
    }

